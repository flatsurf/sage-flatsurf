def number_field_elements_from_algebraics(elts, name="a"):
    r"""
    The native Sage function ``number_field_elements_from_algebraics`` currently
    returns number field *without* embedding. This function return field with
    embedding!

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import number_field_elements_from_algebraics
        sage: z = QQbar.zeta(5)
        sage: c = z.real()
        sage: s = z.imag()
        sage: number_field_elements_from_algebraics((c, s))
        (Number Field in a with defining polynomial y^4 - 5*y^2 + 5
         with a = 1.902113032590308?, [1/2*a^2 - 3/2, 1/2*a])
        sage: number_field_elements_from_algebraics([AA(1), AA(2/3)])
        (Rational Field, [1, 2/3])
    """
    # case when all elements are rationals
    if all(x in QQ for x in elts):
        return QQ, [QQ(x) for x in elts]

    # general case
    from sage.rings.qqbar import number_field_elements_from_algebraics

    field, elts, phi = number_field_elements_from_algebraics(elts, minimal=True)

    polys = [x.polynomial() for x in elts]
    K = NumberField(field.polynomial(), name, embedding=AA(phi(field.gen())))
    gen = K.gen()

    return K, [x.polynomial()(gen) for x in elts]


def subfield_from_elements(self, alpha, name=None, polred=True, threshold=None):
    r"""
    Return the subfield generated by the elements ``alpha``.

    .. NOTE::

        See https://trac.sagemath.org/ticket/29331

    INPUT:

    - ``alpha`` - list of elements in this number field

    - ``name`` - a name for the generator of the new number field

    - ``polred`` (boolean, default ``True``) - whether to optimize the generator of
      the newly created field

    - ``threshold`` (positive number, default ``None``) - threshold to be passed to
      the ``do_polred`` function

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import subfield_from_elements

        sage: x = polygen(QQ)
        sage: poly = x^4 - 4*x^2 + 1
        sage: emb = AA.polynomial_root(poly, RIF(0.51, 0.52))
        sage: K.<a> = NumberField(poly, embedding=emb)
        sage: sqrt2 = -a^3 + 3*a
        sage: sqrt3 = -a^2 + 2
        sage: assert sqrt2 ** 2 == 2 and sqrt3 ** 2 == 3
        sage: L, elts, phi = subfield_from_elements(K, [sqrt2, 1 - sqrt2/3])
        sage: L
        Number Field in a0 with defining polynomial x^2 - 2 with a0 = 1.414213562373095?
        sage: elts
        [a0, -1/3*a0 + 1]
        sage: phi
        Ring morphism:
          From: Number Field in a0 with defining polynomial x^2 - 2 with a0 = 1.414213562373095?
          To:   Number Field in a with defining polynomial x^4 - 4*x^2 + 1 with a = 0.5176380902050415?
          Defn: a0 |--> -a^3 + 3*a
        sage: assert phi(elts[0]) == sqrt2
        sage: assert phi(elts[1]) == 1 - sqrt2/3

        sage: L, elts, phi = subfield_from_elements(K, [1, sqrt3])
        sage: assert phi(elts[0]) == 1
        sage: assert phi(elts[1]) == sqrt3

    TESTS::

        sage: from flatsurf.geometry.subfield import subfield_from_elements
        sage: x = polygen(QQ)

        sage: p = x^8 - 12*x^6 + 23*x^4 - 12*x^2 + 1
        sage: K.<a> = NumberField(p)
        sage: sqrt2 = 6/7*a^7 - 71/7*a^5 + 125/7*a^3 - 43/7*a
        sage: sqrt3 = 3/7*a^6 - 32/7*a^4 + 24/7*a^2 + 10/7
        sage: sqrt5 = 8/7*a^6 - 90/7*a^4 + 120/7*a^2 - 27/7
        sage: assert sqrt2**2 == 2 and sqrt3**2 == 3 and sqrt5**2 == 5
        sage: L, elts, phi = subfield_from_elements(K, [sqrt2, sqrt3], name='b')
        sage: assert phi(elts[0]) == sqrt2
        sage: assert phi(elts[1]) == sqrt3
        sage: L, elts, phi = subfield_from_elements(K, [sqrt2, sqrt5], name='b')
        sage: assert phi(elts[0]) == sqrt2
        sage: assert phi(elts[1]) == sqrt5
        sage: L, elts, phi = subfield_from_elements(K, [sqrt3, sqrt5], name='b')
        sage: assert phi(elts[0]) == sqrt3
        sage: assert phi(elts[1]) == sqrt5
        sage: L, elts, phi = subfield_from_elements(K, [-149582/214245 + 21423/5581*sqrt2], name='b')
        sage: assert L.polynomial() == x^2 - 2
        sage: L, elts, phi = subfield_from_elements(K, [131490/777 - 1359/22*sqrt3], name='b')
        sage: assert L.polynomial() == x^2 - 3
        sage: L, elts, phi = subfield_from_elements(K, [12241829/177 - 321121/22459 * sqrt5], name='b')
        sage: assert L.polynomial() == x^2 - x - 1

        sage: from sage.rings.qqbar import number_field_elements_from_algebraics
        sage: R.<x> = QQ[]
        sage: p1 = x^3 - x - 1
        sage: roots1 = p1.roots(QQbar, False)
        sage: for _ in range(10):  # long time (1.5s)
        ....:     p2 = R.random_element(degree=2)
        ....:     while not p2.is_irreducible(): p2 = R.random_element(degree=2)
        ....:     roots2 = p2.roots(QQbar, False)
        ....:     K, (a1,b1,c1,a2,b2), phi = number_field_elements_from_algebraics(roots1 + roots2)
        ....:     u1 = 1 - a1/17 + 3/7*a1**2
        ....:     u2 = 2 + 33/35 * a1
        ....:     L, (v1,v2), phi = subfield_from_elements(K, [u1, u2], threshold=100)
        ....:     assert L.polynomial() == p1
        ....:     assert phi(v1) == u1 and phi(v2) == u2
    """
    V = VectorSpace(QQ, self.degree())
    alpha = [self(a) for a in alpha]

    # Rational case (degree 0)
    if all(a in QQ for a in alpha):
        return (QQ, [QQ(a) for a in alpha], self.coerce_map_from(QQ))

    # Trivial maximal case (an element generating the field)
    if any(a.minpoly().degree() == self.degree() for a in alpha):
        return (self, alpha, Hom(self, self, Fields()).identity())

    # Saturate with multiplication
    vecs = [(a * a.denominator()).vector() for a in alpha]
    U = V.subspace(vecs)
    modified = True
    while modified:
        modified = False
        d = U.dimension()
        if d == self.degree():
            return (self, alpha, Hom(self, self, Fields()).identity())
        B = U.basis()
        new_vecs = [
            (self(B[i]) * self(B[j])).vector() for i in range(d) for j in range(i, d)
        ]
        if any(vv not in U for vv in new_vecs):
            U = V.subspace(list(B) + new_vecs)
            modified = True

    # Strict subfield, find a generator
    vgen = None
    for b in U.basis():
        if self(b).minpoly().degree() == d:
            vgen = b
            break
    if vgen is None:
        s = 1
        while True:
            vgen = U.random_element(proba=0.5, x=-s, y=s)
            if self(vgen).minpoly().degree() == d:
                break
            s *= 2

    # Minimize the generator via PARI polred
    gen = self(vgen)
    p = gen.minpoly()
    if polred:
        if threshold:
            fwd, back, q = do_polred(p, threshold)
        else:
            fwd, back, q = do_polred(p)
    else:
        q = p
        fwd = back = self.polynomial_ring().gen()

    new_gen = fwd(gen)
    assert new_gen.minpoly() == q
    K, hom = self.subfield(new_gen, name=name)

    # need to express the elements in the basis 1, a, a^2, ..., a^(d-1)
    M = matrix(QQ, [(new_gen**i).vector() for i in range(d)])
    new_alpha = [K(M.solve_left(elt.vector())) for elt in alpha]

    return (K, new_alpha, hom)


def is_embedded_subfield(K, L, certificate=False):
    r"""
    Return whether there exists a field morphism from ``K`` to ``L`` compatible with
    the embeddings.

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import is_embedded_subfield

        sage: x = polygen(QQ)
        sage: y = polygen(QQ, 'y')
        sage: z = polygen(QQ, 'z')
        sage: p = x^4 - 4*x^2 + 1
        sage: emb = AA.polynomial_root(p, RIF(0.5, 0.6))
        sage: L = NumberField(p, 'a', embedding=emb)
        sage: K1 = NumberField(y^2 - 2, 'sqrt2', embedding=AA(2)**(1/2))
        sage: K2 = NumberField(z^2 - 2, 'msqrt2', embedding=-AA(2)**(1/2))
        sage: is_embedded_subfield(K1, L)
        True
        sage: is_embedded_subfield(K1, L, True)
        (True, Generic morphism:
           From: Number Field in sqrt2 with defining polynomial y^2 - 2 with sqrt2 = 1.414213562373095?
           To:   Number Field in a with defining polynomial x^4 - 4*x^2 + 1 with a = 0.5176380902050415?
           Defn: sqrt2 -> -a^3 + 3*a)
        sage: is_embedded_subfield(K2, L, True)
        (True, Generic morphism:
           From: Number Field in msqrt2 with defining polynomial z^2 - 2 with msqrt2 = -1.414213562373095?
           To:   Number Field in a with defining polynomial x^4 - 4*x^2 + 1 with a = 0.5176380902050415?
           Defn: msqrt2 -> a^3 - 3*a)
        sage: is_embedded_subfield(K1, K2, True)
        (True, Generic morphism:
           From: Number Field in sqrt2 with defining polynomial y^2 - 2 with sqrt2 = 1.414213562373095?
           To:   Number Field in msqrt2 with defining polynomial z^2 - 2 with msqrt2 = -1.414213562373095?
           Defn: sqrt2 -> -msqrt2)
    """
    assert K.coerce_embedding() is not None
    assert L.coerce_embedding() is not None
    assert K.coerce_embedding().codomain() == L.coerce_embedding().codomain()
    pK = K.polynomial()
    pL = L.polynomial()
    emb = K.coerce_embedding().gen_image()
    P = pL.parent()
    pK = P(pK)
    phi = L.coerce_embedding()
    for r in pK.roots(L, multiplicities=False):
        if phi(r) == emb:
            return (True, K.hom(L, [r])) if certificate else True
    return (False, None) if certificate else False


def chebyshev_T(n, c):
    r"""
    Return the Chebyshev polynomial T_n so that

    T_n(2 cos(x)) = 2 cos(n x)

    .. NOTE::

        We use the polynomial as defined in [KoRoTr2015]_,
        not the Sage version which uses a different normalization.

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import chebyshev_T, cos_minpoly

        sage: x = polygen(ZZ)

        sage: chebyshev_T(1, x) - 1 == cos_minpoly(3, x)
        True
        sage: chebyshev_T(2, x) - chebyshev_T(1, x) + 1 == cos_minpoly(5, x)
        True
        sage: chebyshev_T(3, x) - chebyshev_T(2, x) + chebyshev_T(1, x) - 1 == cos_minpoly(7, x)
        True

        sage: cos_minpoly(5, x)(chebyshev_T(3, x)) == cos_minpoly(15, x) * cos_minpoly(5, x)
        True
        sage: cos_minpoly(3, x)(chebyshev_T(5, x)) == cos_minpoly(15, x) * cos_minpoly(3, x)
        True
    """
    # T_0(x) = 2
    # T_1(x) = x
    # and T_{n+1}(x) = x T_n(x) - T_{n-1}(x)
    T0 = parent(c)(2)
    if n == 0:
        return T0
    T1 = c
    for i in range(n - 1):
        T0, T1 = T1, c * T1 - T0
    return T1


def cos_minpoly_odd_prime(p, var):
    r"""
    (-1)^k + (-1)^{k-1} T1 + ... + T_k

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import cos_minpoly_odd_prime

        sage: x = polygen(ZZ)

        sage: cos_minpoly_odd_prime(3, x)
        x - 1
        sage: cos_minpoly_odd_prime(5, x)
        x^2 - x - 1
        sage: cos_minpoly_odd_prime(7, x)
        x^3 - x^2 - 2*x + 1
        sage: cos_minpoly_odd_prime(11, x)
        x^5 - x^4 - 4*x^3 + 3*x^2 + 3*x - 1
    """
    T0 = 2
    T1 = var
    k = (p - 1) // 2
    s = (-1) ** k
    minpoly = s * (1 - T1)
    for i in range(k - 1):
        T0, T1 = T1, var * T1 - T0
        minpoly += s * T1
        s *= -1
    return minpoly


def cos_minpoly(n, var="x"):
    r"""
    Return the minimal polynomial of 2 cos pi/n

    Done via [KoRoTr2015]_ Algorithm 3.

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import cos_minpoly

        sage: cos_minpoly(1)
        x + 2
        sage: cos_minpoly(2)
        x
        sage: cos_minpoly(3)
        x - 1
        sage: cos_minpoly(4)
        x^2 - 2
        sage: cos_minpoly(5)
        x^2 - x - 1
        sage: cos_minpoly(6)
        x^2 - 3
        sage: cos_minpoly(8)
        x^4 - 4*x^2 + 2
        sage: cos_minpoly(9)
        x^3 - 3*x - 1
        sage: cos_minpoly(10)
        x^4 - 5*x^2 + 5

        sage: cos_minpoly(90)
        x^24 - 24*x^22 + 252*x^20 - 1519*x^18 + 5796*x^16 - 14553*x^14 + 24206*x^12 - 26169*x^10 + 17523*x^8 - 6623*x^6 + 1182*x^4 - 72*x^2 + 1
        sage: cos_minpoly(148)
        x^72 - 72*x^70 + 2483*x^68 - 54604*x^66 + 860081*x^64 ... - 3511656*x^6 + 77691*x^4 - 684*x^2 + 1
    """
    n = ZZ(n)
    facs = list(n.factor())
    if isinstance(var, str):
        var = polygen(ZZ, var)

    if not facs:
        # 2 cos (pi) = -2
        return var + 2
    if facs[0][0] == 2:  # n is even
        k = facs[0][1]
        facs.pop(0)
    else:
        k = 0

    if not facs:
        # 0. n = 2^k
        # ([KoRoTr2015] Lemma 12)
        return chebyshev_T(2 ** (k - 1), var)

    # 1. Compute M_{n0} = M_{p1 ... ps}
    # ([KoRoTr2015] Lemma 14 and Lemma 15)
    M = cos_minpoly_odd_prime(facs[0][0], var)
    for i in range(1, len(facs)):
        p = facs[i][0]
        M, r = M(chebyshev_T(p, var)).quo_rem(M)
        assert r.is_zero()

    # 2. Compute M_{2^k p1^{a1} ... ps^{as}}
    # ([KoRoTr2015] Lemma 12)
    nn = 2**k * prod(p ** (a - 1) for p, a in facs)
    if nn != 1:
        M = M(chebyshev_T(nn, var))

    return M


def _triangle_invariant_trace_field(angles):
    r"""
    Return the field `\QQ(u_0, u_1, u_2, p)` with `u_k = 4 \cos^2 \alpha_k`
    and `p = 8 \cos \alpha_0 \cos \alpha_1 \cos \alpha_2`, together with
    these elements.

    For the angles `\pi / m_k` this is the invariant trace field of the
    triangle group of periods `(m_0, m_1, m_2)`.

    INPUT:

    - ``angles`` -- three rationals `\theta_0, \theta_1, \theta_2`, the angles
      `\alpha_k = 2 \pi \theta_k` in multiples of `2 \pi`

    OUTPUT:

    A triple ``(K, u, p)``: ``K`` is ``QQ`` or a number field embedded in the
    reals, whose defining polynomial is reduced by PARI's ``polredbest``;
    ``u`` is the tuple `(u_0, u_1, u_2)` of elements of ``K``, in the order
    of ``angles``; ``p`` is an element of ``K``. The embedding of ``K`` is the
    one where `u_k = 4 \cos^2 \alpha_k` and
    `p = 8 \cos \alpha_0 \cos \alpha_1 \cos \alpha_2` as real numbers.

    EXAMPLES:

    The triangle group `(2, 3, 7)` has a cubic invariant trace field; `p` is
    zero because of the right angle::

        sage: from flatsurf.geometry.subfield import _triangle_invariant_trace_field
        sage: K, u, p = _triangle_invariant_trace_field([1/4, 1/6, 1/14])
        sage: K
        Number Field in a with defining polynomial x^3 - 7*x - 7 with a = 3.048917339522306?
        sage: u
        (0, 1, a^2 - a - 3)
        sage: p
        0

    The triangle group `(5, 7, 8)` has an invariant trace field of degree
    `24`::

        sage: K, u, p = _triangle_invariant_trace_field([1/10, 1/14, 1/16])
        sage: K.degree()
        24
        sage: u[0] * u[1] * u[2] == p^2
        True
        sage: AA(u[2]) == 4 * AA(QQbar.zeta(16).real())^2
        True

    A cusp, of angle `0`, has `u = 4`; the triangle group `(2, 3, \infty)`
    has invariant trace field `\QQ`::

        sage: K, u, p = _triangle_invariant_trace_field([0, 1/4, 1/6])
        sage: K
        Rational Field
        sage: u, p
        ((4, 0, 1), 0)

    TESTS:

    A quadratic field, with `p` nonzero::

        sage: K, u, p = _triangle_invariant_trace_field([1/6, 1/6, 1/8])
        sage: K.degree()
        2
        sage: K.polynomial()
        x^2 - 2
        sage: u, p
        ((1, 1, 2), a)

    An angle given as a Python ``int``::

        sage: K, u, p = _triangle_invariant_trace_field([int(0), 1/4, 1/6])
        sage: K is QQ
        True

    ALGORITHM:

    With `N` the least common multiple of the denominators of the
    `\theta_k`, the elements `\cos \alpha_k` lie in `\QQ(\zeta_N)`, where
    `\sigma_j`, `j \in (\ZZ/N)^\times`, sends `\cos(2 \pi \theta)` to
    `\cos(2 \pi j \theta)`. So `\sigma_j` fixes `u_k` if and only if
    `2 j \theta_k = \pm 2 \theta_k + t_k` with an integer `t_k`, and then
    sends `p` to `(-1)^{t_0 + t_1 + t_2} p`. These congruences give the
    subgroup `H` fixing ``K``, and the conjugates of an element of ``K`` are
    explicit cosines over the cosets of `H`.

    The element `s = u_0 + t u_1 + t^2 u_2 + t^3 p`, for the first integer
    `t \ge 0` whose conjugates are pairwise distinct, generates ``K``. It is
    an algebraic integer: its minimal polynomial is the product of the
    `x - \sigma(s)` computed in interval arithmetic, each coefficient
    rounded to the unique integer of its interval. The precision covers the
    bound `(1 + B)^d` on the coefficients, with `d = [K : \QQ]` and `B` the
    bound `4 (1 + t + t^2) + 8 t^3` on the conjugates, and is doubled when
    the intervals are too wide. PARI's ``polredbest`` then reduces this
    polynomial, and the embedding is the real root where `s` takes its value
    at `j = 1`. Each `u_k` is the root in ``K`` of its minimal polynomial,
    which ``cos_minpoly`` gives, near its value, and `p` the square root of
    `u_0 u_1 u_2` of the sign of its value.
    """
    from sage.libs.pari import pari
    from sage.rings.real_mpfi import RealIntervalField

    angles = [QQ(angle) for angle in angles]

    N = ZZ.one()
    for angle in angles:
        N = N.lcm(angle.denominator())
    units = [j for j in range(1, N + 1) if ZZ(j).gcd(N) == 1]

    # cos(2 pi theta) = 0 exactly when theta = 1/4 or 3/4 mod 1
    p_is_zero = any(angle.denominator() == 4 for angle in angles)

    def fixes(j):
        sign = 1
        for angle in angles:
            if (2 * (j - 1) * angle) in ZZ:
                t = ZZ(2 * (j - 1) * angle)
            elif (2 * (j + 1) * angle) in ZZ:
                t = ZZ(2 * (j + 1) * angle)
            else:
                return False
            sign *= (-1) ** t
        return p_is_zero or sign == 1

    H = [j for j in units if fixes(j)]
    cosets = []
    seen = set()
    for j in units:
        if j in seen:
            continue
        cosets.append(j)
        seen.update(j * h % N for h in H)
    d = ZZ(len(cosets))
    assert d * len(H) == len(units)

    x = polygen(ZZ, "x")

    def conjugate_cosines(R):
        two_pi = 2 * R.pi()
        cosines = []
        for j in cosets:
            reduced = [j * angle - (j * angle).floor() for angle in angles]
            cosines.append([(two_pi * R(r)).cos() for r in reduced])
        return cosines

    def distinct(values):
        return not any(
            values[i].overlaps(values[k]) for i in range(len(values)) for k in range(i)
        )

    # Two distinct conjugates of s differ by a nonzero polynomial of degree
    # at most 3 in t, so each of the d (d - 1) / 2 pairs excludes at most 3
    # values of t.
    t_bound = 3 * d * (d - 1) // 2

    prec = 64
    while True:
        R = RealIntervalField(prec)
        cosines = conjugate_cosines(R)
        conjugates_u = [[4 * c**2 for c in cs] for cs in cosines]
        conjugates_p = [8 * cs[0] * cs[1] * cs[2] for cs in cosines]

        for t in range(t_bound + 1):
            values = [
                us[0] + t * us[1] + t**2 * us[2] + t**3 * pp
                for us, pp in zip(conjugates_u, conjugates_p)
            ]
            if distinct(values):
                break
        else:
            prec *= 2
            continue

        bound = 4 * (1 + t + t**2) + 8 * t**3
        required = d * ZZ(1 + bound).nbits() + d.nbits() + 32
        if prec < required:
            prec = required
            continue

        coefficients = prod(x.change_ring(R) - v for v in values).list()
        if all(c.lower().ceil() == c.upper().floor() for c in coefficients):
            f = x.parent()([c.unique_integer() for c in coefficients])
            break
        prec *= 2

    if d == 1:
        K = QQ

        def real(y):
            return R(y)

    else:
        g, s = pari(f).polredbest(1)
        g = x.parent()(g)
        s = QQ["y"](s.lift())
        roots = [
            beta
            for beta in g.roots(AA, multiplicities=False)
            if s(R(beta)).overlaps(values[0])
        ]
        assert len(roots) == 1
        K = NumberField(g, "a", embedding=roots[0])
        beta = R(roots[0])

        def real(y):
            return y.polynomial()(beta)

    def root(polynomial, value):
        roots = [
            r
            for r in polynomial.roots(K, multiplicities=False)
            if real(r).overlaps(value)
        ]
        assert len(roots) == 1
        return roots[0]

    u = []
    for angle, value in zip(angles, conjugates_u[0]):
        # u = 2 + 2 cos(2 pi a / b) with a / b = 2 theta in lowest terms;
        # 2 cos(2 pi a / b) is a conjugate of 2 cos(pi / (b / 2)) for b even
        # and of -2 cos(pi / b) for b odd.
        b = (2 * angle).denominator()
        if b % 2 == 0:
            minpoly = cos_minpoly(b // 2)(x - 2)
        else:
            minpoly = cos_minpoly(b)(2 - x)
        u.append(root(minpoly, value))

    if p_is_zero:
        p = K.zero()
    else:
        p = root(x**2 - u[0] * u[1] * u[2], conjugates_p[0])

    return K, tuple(u), p


def _check_exact(ring):
    r"""
    Raise a ``ValueError`` if ``ring`` is an inexact ring.

    The closure, convexity and angle checks of a polygon, and the checks on
    gluings and fields, are unreliable after rounding.

    INPUT:

    - ``ring`` -- a ring or ``None``

    EXAMPLES::

        sage: from flatsurf.geometry.subfield import _check_exact
        sage: _check_exact(None)
        sage: _check_exact(QQ)
        sage: _check_exact(RDF)
        Traceback (most recent call last):
        ...
        ValueError: the ring must be exact, not Real Double Field

    """
    if ring is not None and not ring.is_exact():
        raise ValueError(f"the ring must be exact, not {ring}")
