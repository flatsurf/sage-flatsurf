from sage.categories.morphism import Morphism


def holonomy_representation(surface, base_label=None, punctured_vertices=True):
    r"""
    Return the holonomy representation of the oriented cone ``surface``.

    This is a helper function for
    :meth:`~flatsurf.geometry.categories.common_cone_surfaces.ConeSurfaces.FiniteType.Oriented.ParentMethods.holonomy_representation`,
    which documents the arguments.

    The codomain is chosen from the category of ``surface``: the group of
    isometries of the hyperbolic plane of the surface over the base ring for
    a hyperbolic surface, the group of similarities over the base ring
    otherwise, the parents of the ``edge_transformation`` of the surface. So
    it does not need a glued edge.

    EXAMPLES::

        sage: from flatsurf import translation_surfaces
        sage: from flatsurf.geometry.holonomy import holonomy_representation
        sage: S = translation_surfaces.square_torus()
        sage: holonomy_representation(S, punctured_vertices=False).codomain()
        Similarity group over Rational Field

    A hyperbolic surface on the plane with the form `x^2 + 3y^2 - z^2`::

        sage: from flatsurf import HyperbolicPlane
        sage: from flatsurf.geometry.hyperbolic_surface import MutableOrientedHyperbolicSurface
        sage: H = HyperbolicPlane(QQ, form=[1, 3, -1])
        sage: S = MutableOrientedHyperbolicSurface(H)
        sage: S.add_polygon(H.polygon(vertices=[(0, 0), (1/2, 0), (-1/4, 1/4)]))
        0
        sage: S.glue((0, 0), (0, 2))
        sage: S.glue((0, 1), (0, 1))
        sage: S.set_immutable()
        sage: holonomy_representation(S).codomain()
        Group of isometries of the hyperbolic plane over Rational Field with form x^2 + 3*y^2 - z^2

    TESTS::

        sage: from flatsurf import Polygon, MutableOrientedSimilaritySurface
        sage: S = MutableOrientedSimilaritySurface(QQ)
        sage: S.add_polygon(Polygon(vertices=[(0, 0), (1, 0), (1, 1), (0, 1)]))
        0
        sage: S.glue((0, 0), (0, 1))
        sage: S.glue((0, 2), (0, 3))
        sage: S.set_immutable()
        sage: holonomy_representation(S, punctured_vertices=[S(0, 0), S(0, 1)])
        Traceback (most recent call last):
        ...
        ValueError: cannot fill the vertex Vertex 3 of polygon 0 whose angle 1/4 is not an integer multiple of 2π
    """
    from sage.all import ZZ

    from flatsurf.geometry.categories import HyperbolicConeSurfaces

    K = surface.base_ring()
    if surface in HyperbolicConeSurfaces():
        from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup

        G = HyperbolicIsometryGroup(K, form=surface.hyperbolic_plane()._form)
    else:
        from flatsurf.geometry.similarity import SimilarityGroup

        G = SimilarityGroup(K)

    F = surface.fundamental_group(
        base_label=base_label, punctured_vertices=punctured_vertices
    )

    if not F._all_punctured:
        # Filling a vertex adds its loop as a relation, which holds in the
        # image only when the loop maps to a rotation by a multiple of 2π.
        for vertex in F.vertex_loops():
            if vertex in F._punctured_vertices:
                continue
            try:
                angle = vertex.angle()
            except ValueError:
                # The angle is not a rational multiple of 2π.
                angle = vertex.angle(numerical=True)
            else:
                if angle in ZZ:
                    continue
            raise ValueError(
                f"cannot fill the vertex {vertex} whose angle {angle} is not an integer multiple of 2π"
            )

    from sage.categories.homset import Hom

    parent = Hom(F, G)
    # The class of the morphism must derive from the element class of the
    # category of its homset, as for the other morphisms of Sage defined in
    # Python.
    return parent.__make_element_class__(HolonomyRepresentation)(parent)


class HolonomyRepresentation(Morphism):
    r"""
    The holonomy representation of an oriented cone surface built from
    finitely many polygons.

    INPUT:

    - ``parent`` -- the homset from a
      :class:`~flatsurf.geometry.fundamental_group.FundamentalGroup` of the
      surface to the group of the ``edge_transformation`` of the surface

    EXAMPLES:

    The square glued by rotations of angle π/2 has three vertices, of angles
    `1/4`, `1/4` and `1/2`. Their loops map to the rotations about the
    developed vertices::

        sage: from flatsurf import Polygon, MutableOrientedSimilaritySurface
        sage: P = Polygon(vertices=[(0, 0), (1, 0), (1, 1), (0, 1)])
        sage: S = MutableOrientedSimilaritySurface(QQ)
        sage: S.add_polygon(P, label=0)
        0
        sage: S.glue((0, 0), (0, 1))
        sage: S.glue((0, 2), (0, 3))
        sage: S.set_immutable()
        sage: phi = S.holonomy_representation()
        sage: F = phi.domain()
        sage: x, y = F.gens()
        sage: loops = F.vertex_loops()
        sage: phi(loops[S(0, 1)]).matrix()
        [ 0 -1  1]
        [ 1  0 -1]
        [ 0  0  1]
        sage: phi(loops[S(0, 3)]).matrix()
        [ 0 -1  1]
        [ 1  0  1]
        [ 0  0  1]
        sage: phi(loops[S(0, 0)]).matrix()
        [-1  0  2]
        [ 0 -1  2]
        [ 0  0  1]
        sage: phi(x * y) == phi(x) * phi(y)
        True
        sage: TestSuite(phi).run()

    A sphere glued from a Lambert quadrilateral, with vertices of angles
    `1/4`, `1/2` and an irrational one; the trace of a rotation by `2\pi a`
    is `1 + 2\cos(2\pi a)`::

        sage: from flatsurf import HyperbolicPlane
        sage: from flatsurf.geometry.hyperbolic_surface import MutableOrientedHyperbolicSurface
        sage: H = HyperbolicPlane(QQ)
        sage: S = MutableOrientedHyperbolicSurface(QQ)
        sage: S.add_polygon(H.polygon(vertices=[(0, 0), (1/2, 0), (1/2, 1/2), (0, 1/2)]))
        0
        sage: S.glue((0, 0), (0, 3))
        sage: S.glue((0, 1), (0, 2))
        sage: S.set_immutable()
        sage: phi = S.holonomy_representation()
        sage: phi
        Holonomy morphism:
          From: Fundamental group of Genus 0 Hyperbolic Surface built from a quadrilateral punctured at all of its vertices based at polygon 0
          To:   Group of isometries of the hyperbolic plane over Rational Field
        sage: loops = phi.domain().vertex_loops()
        sage: [phi(loops[S(0, i)]).trace() for i in range(3)]
        [1, -1, 5/3]
        sage: TestSuite(phi).run()

    """

    def _repr_type(self):
        r"""
        Return the kind of this morphism, printed by ``repr``.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: translation_surfaces.square_torus().holonomy_representation()._repr_type()
            'Holonomy'
        """
        return "Holonomy"

    def _develop(self, letters):
        r"""
        Return the product of the ``edge_transformation`` of the ``letters``.

        The ``letters`` are the edges through which a walk, not necessarily
        closed, enters its successive polygons; the product sends the
        coordinates of the last polygon of the walk into those of its first
        polygon.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: S = translation_surfaces.veech_double_n_gon(5)
            sage: phi = S.holonomy_representation()
            sage: phi._develop(()).is_one()
            True
            sage: phi._develop(((1, 4),)) == S.edge_transformation(1, 4)
            True
        """
        surface = self.domain()._s
        g = self.codomain().one()
        for letter in letters:
            g = g * surface.edge_transformation(*letter)
        return g

    def _call_(self, x):
        r"""
        Return the image of the element ``x`` of the fundamental group.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: S = translation_surfaces.square_torus()
            sage: phi = S.holonomy_representation()
            sage: a, b = phi.domain().gens()
            sage: phi(a * b)
            (x, y) |-> (x + 1, y - 1)
            sage: phi(a * ~a).is_one()
            True
        """
        return self._develop(x._walk)

    def image(self):
        r"""
        Return the image of this representation, as the subgroup of the
        codomain generated by the images of the generators of the fundamental
        group.

        The codomain is the group of similarities on a flat surface, the group
        of isometries of the hyperbolic plane on a hyperbolic surface. The
        elements of the image are similarities on a flat surface, and
        isometries of `\mathrm{SO}(Q)^+`, for the quadratic form `Q` of the
        hyperbolic plane, acting on the Klein model on a hyperbolic surface.
        The method ``matrix_group()`` of the subgroup gives the group of their
        `3 \times 3` matrices over the base ring. When the fundamental group
        has no generator, the subgroup has no generator.

        EXAMPLES:

        The pillowcase has the wallpaper group p2 as uniformisation group::

            sage: from flatsurf import polygons, similarity_surfaces
            sage: S = similarity_surfaces.pillowcase(polygons.square())
            sage: G = S.holonomy_representation().image()
            sage: G
            Subgroup with 3 generators of Similarity group over Rational Field
            sage: G.matrix_group()
            Matrix group over Rational Field with 3 generators (
            [-1  0  0]  [1 0 2]  [-1  0  0]
            [ 0 -1  0]  [0 1 0]  [ 0 -1  2]
            [ 0  0  1], [0 0 1], [ 0  0  1]
            )
            sage: G.is_orientable()
            True

        A polygon with no gluing has an image with no generator::

            sage: from flatsurf import Polygon, MutableOrientedSimilaritySurface
            sage: S = MutableOrientedSimilaritySurface(QQ)
            sage: S.add_polygon(Polygon(vertices=[(0, 0), (1, 0), (0, 1)]))
            0
            sage: S.set_immutable()
            sage: S.holonomy_representation().image()
            Subgroup with 0 generators of Similarity group over Rational Field
        """
        return self.codomain().subgroup([self(g) for g in self.domain().gens()])

    def _is_hyperbolic(self):
        r"""
        Return whether the codomain is a group of hyperbolic isometries.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: translation_surfaces.square_torus().holonomy_representation()._is_hyperbolic()
            False
        """
        from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup

        return isinstance(self.codomain(), HyperbolicIsometryGroup)

    def invariant_trace_field(self):
        r"""
        Return the field generated by the `\mathrm{SO}(2, 1)` traces of the
        image of this representation, for a hyperbolic surface.

        OUTPUT:

        ``QQ`` or a number field, embedded in the reals when the base ring is
        ``AA`` or an embedded number field.

        For a non-elementary group, e.g. the image of a hyperbolic surface of
        negative Euler characteristic with divisor, this is the invariant
        trace field `k\Gamma` of Maclachlan and Reid, *The Arithmetic of
        Hyperbolic 3-Manifolds* (2003), chapter 3: the field of the traces of
        the squares, i.e. of the `\mathrm{SO}(2, 1)` traces
        `\mathrm{tr}(A)^2 - 1`. It is contained in the field of the
        `\mathrm{PSL}_2` traces. Unlike the base ring of the surface, it is a
        conjugacy invariant of the image.

        It is the field of the subgroup :meth:`image`, see
        :meth:`~flatsurf.geometry.hyperbolic_isometry.HyperbolicIsometrySubgroup.invariant_trace_field`
        for the algorithm.

        EXAMPLES:

        The sphere glued from a Lambert quadrilateral::

            sage: from flatsurf import HyperbolicPlane
            sage: from flatsurf.geometry.hyperbolic_surface import MutableOrientedHyperbolicSurface
            sage: H = HyperbolicPlane(QQ)
            sage: S = MutableOrientedHyperbolicSurface(QQ)
            sage: S.add_polygon(H.polygon(vertices=[(0, 0), (1/2, 0), (1/2, 1/2), (0, 1/2)]))
            0
            sage: S.glue((0, 0), (0, 3))
            sage: S.glue((0, 1), (0, 2))
            sage: S.set_immutable()
            sage: S.holonomy_representation().invariant_trace_field()
            Rational Field

        The regular octagon of angle π/4 is defined over a field of degree 4,
        but its group has traces in `\QQ(\sqrt{2})`::

            sage: K.<r> = NumberField(x^4 + 32*x^2 - 32, embedding=AA(12*AA(2).sqrt() - 16).sqrt())
            sage: s2 = r^2/12 + 4/3
            sage: cos = [1, s2/2, 0, -s2/2, -1, -s2/2, 0, s2/2]
            sage: sin = [0, s2/2, 1, s2/2, 0, -s2/2, -1, -s2/2]
            sage: P = HyperbolicPlane(K).polygon(vertices=[(r * c, r * s) for c, s in zip(cos, sin)])
            sage: S = MutableOrientedHyperbolicSurface(K)
            sage: S.add_polygon(P)
            0
            sage: for i in range(4):
            ....:     S.glue((0, i), (0, i + 4))
            sage: S.set_immutable()
            sage: S.base_ring().degree()
            4
            sage: S.holonomy_representation().invariant_trace_field()
            Number Field in r0 with defining polynomial x^2 - 2 with r0 = 1.414213562373095?

        A flat surface is not supported::

            sage: from flatsurf import translation_surfaces
            sage: translation_surfaces.square_torus().holonomy_representation().invariant_trace_field()
            Traceback (most recent call last):
            ...
            NotImplementedError: the invariant trace field is only implemented for hyperbolic surfaces

        TESTS:

        The same octagon over the algebraic reals::

            sage: S.change_ring(AA).holonomy_representation().invariant_trace_field()
            Number Field in a with defining polynomial y^2 - 2 with a = 1.414213562373095?

        Katok's gluing of the octagon::

            sage: T = MutableOrientedHyperbolicSurface(K)
            sage: T.add_polygon(P)
            0
            sage: for a, b in [(0, 2), (1, 3), (4, 6), (5, 7)]:
            ....:     T.glue((0, a), (0, b))
            sage: T.set_immutable()
            sage: T.holonomy_representation().invariant_trace_field()
            Number Field in r0 with defining polynomial x^2 - 2 with r0 = 1.414213562373095?

        A polygon without gluing has no generator::

            sage: U = MutableOrientedHyperbolicSurface(QQ)
            sage: U.add_polygon(H.polygon(vertices=[(0, 0), (1/2, 0), (1/2, 1/2), (0, 1/2)]))
            0
            sage: U.set_immutable()
            sage: U.holonomy_representation().invariant_trace_field()
            Rational Field

        The double of the triangle of angles `\pi/4, \pi/5, \pi/2` at its
        vertices `0, 1, 2`, glued to its mirror image along its three edges,
        has the group of the triangle of periods `(2, 4, 5)`, whose invariant
        trace field is `\QQ(\sqrt{5})` by Proposition 5 of Takeuchi,
        *Arithmetic triangle groups* (1977). A generator is a half-turn, of
        `\mathrm{SO}(2, 1)` trace `-1`::

            sage: K.<a> = NumberField(x^4 - 2*x^2 - 4, embedding=-1.8)
            sage: u, v = -2*a + a^3/2, -a + a^3/4
            sage: H = HyperbolicPlane(K)
            sage: S = MutableOrientedHyperbolicSurface(K)
            sage: S.add_polygon(H.polygon(vertices=[(0, 0), (u, 0), (v, v)]))
            0
            sage: S.add_polygon(H.polygon(vertices=[(u, 0), (0, 0), (v, -v)]))
            1
            sage: for i in range(3):
            ....:     S.glue((0, i), (1, -i % 3))
            sage: S.set_immutable()
            sage: phi = S.holonomy_representation()
            sage: [phi(g).trace() for g in phi.domain().gens()]
            [1, -1]
            sage: phi.invariant_trace_field()
            Number Field in a0 with defining polynomial x^2 - x - 1 with a0 = 1.618033988749895?
        """
        if not self._is_hyperbolic():
            raise NotImplementedError(
                "the invariant trace field is only implemented for hyperbolic surfaces"
            )

        return self.image().invariant_trace_field()

    def _developed_vertices(self):
        r"""
        Return the developed vertices of the interior vertices of the surface.

        The loop of a vertex ``v`` (see
        :meth:`~flatsurf.geometry.fundamental_group.FundamentalGroup.vertex_loops`)
        starts at its first corner ``(q_0, j_0)`` and is conjugated by the walk
        in the spanning tree to the polygon ``q_{k-1}`` of the edge glued to
        the edge ``j_0`` of ``q_0``. The developed vertex is the vertex
        ``j_{k-1}``, one after that glued edge, of ``q_{k-1}``, sent into the
        coordinates of the base polygon by that walk.

        OUTPUT:

        A dictionary from the vertices with a loop to vectors, in Klein
        coordinates on a hyperbolic surface.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: S = translation_surfaces.square_torus()
            sage: S.holonomy_representation()._developed_vertices()
            {Vertex 0 of polygon 0: (0, 1)}
        """
        from sage.modules.free_module_element import vector

        F = self.domain()
        surface = F._s
        K = self.codomain().base_ring()
        loops = F.vertex_loops()

        developed = {}
        for q0, j0 in surface.edges():
            # pylint: disable-next=not-callable
            vertex = surface(q0, j0)
            if vertex not in loops or vertex in developed:
                continue
            q, j = surface.opposite_edge(q0, j0)
            polygon = surface.polygon(q)
            j = (j + 1) % len(polygon.vertices())
            point = polygon.vertex(j)
            if self._is_hyperbolic():
                point = point.coordinates(model="klein")
            point = vector(K, point)
            developed[vertex] = self._develop(F._tree_walk(q)) * point
        return developed

    def _test_vertex_loops(self, **options):
        r"""
        Verify that the loop of each interior vertex maps to the rotation
        about the developed vertex by the angle of the vertex.

        The rotation part is compared numerically with the sum of the corner
        angles, and also exactly, in the algebraic reals, when the base ring
        coerces into them (in the rationals otherwise, when the cosine and the
        sine of the angle are rational). When the angle is a
        rational `p/q`, the `q`-th power of the image is checked to be the
        identity.

        EXAMPLES::

            sage: from flatsurf import translation_surfaces
            sage: S = translation_surfaces.veech_double_n_gon(5)
            sage: S.holonomy_representation()._test_vertex_loops()

        A vertex whose cosine is not rational::

            sage: from flatsurf import HyperbolicPlane, similarity_surfaces, Polygon
            sage: from flatsurf.geometry.hyperbolic_surface import MutableOrientedHyperbolicSurface
            sage: x = polygen(QQ)
            sage: K = NumberField(x^4 + 32*x^2 - 32, "r", embedding=RR(0.98))
            sage: r = K.gen(); s2 = r^2/12 + 4/3
            sage: H = HyperbolicPlane(K)
            sage: S = MutableOrientedHyperbolicSurface(K)
            sage: S.add_polygon(H.polygon(vertices=[(0, 0), (r, 0), (r*s2/2, r*s2/2)]))
            0
            sage: S.glue((0, 0), (0, 2)); S.set_immutable()
            sage: phi = S.holonomy_representation()
            sage: phi(phi.domain().vertex_loops()[S(0, 0)]).trace()
            1/12*r^2 + 7/3
            sage: phi._test_vertex_loops()

        The double of a triangle, with irrational sines::

            sage: S = similarity_surfaces.pillowcase(Polygon(angles=(1, 2, 3)))
            sage: S.holonomy_representation()._test_vertex_loops()
        """
        import math

        from sage.all import AA, QQ, QQbar

        tester = self._tester(**options)

        F = self.domain()
        loops = F.vertex_loops()
        developed = self._developed_vertices()
        hyperbolic = self._is_hyperbolic()
        exact = AA.has_coerce_map_from(self.codomain().base_ring())

        for vertex, loop in loops.items():
            g = self(loop)
            point = developed[vertex]
            tester.assertEqual(g * point, point)

            numerical = float(vertex.angle(numerical=True))
            try:
                angle = QQ(vertex.angle())
            except (ValueError, TypeError):
                angle = None

            cos, sin = None, None
            if angle is not None:
                tester.assertTrue(
                    (g ** angle.denominator()).is_one(),
                )
                z = QQbar.zeta(angle.denominator()) ** angle.numerator()
                cos, sin = AA(z.real()), AA(z.imag())

            # The numerical comparison always runs: the numerical angle is the
            # sum of the corner angles, whereas the exact angle of a hyperbolic
            # vertex with irrational corners is read from the trace of g, so
            # comparing g with it alone would check nothing.
            if hyperbolic:
                if cos is not None:
                    if exact:
                        tester.assertEqual(AA(g.trace()), 1 + 2 * cos)
                    elif cos in QQ:
                        tester.assertEqual(g.trace(), 1 + 2 * QQ(cos))
                tester.assertAlmostEqual(
                    float(g.trace()),
                    1 + 2 * math.cos(2 * math.pi * numerical),
                    delta=1e-6,
                )
            else:
                linear = g.matrix().submatrix(0, 0, 2, 2)
                if cos is not None:
                    if exact:
                        tester.assertEqual(
                            [AA(entry) for entry in linear.list()],
                            [cos, -sin, sin, cos],
                        )
                    elif cos in QQ and sin in QQ:
                        c, s = QQ(cos), QQ(sin)
                        tester.assertEqual(linear, linear.parent()([c, -s, s, c]))
                c = math.cos(2 * math.pi * numerical)
                s = math.sin(2 * math.pi * numerical)
                for entry, expected in zip(linear.list(), [c, -s, s, c]):
                    tester.assertAlmostEqual(float(entry), expected, delta=1e-6)


def _holonomy_angle(surface, vertex):
    r"""
    Return the total angle at the interior ``vertex`` of the hyperbolic
    ``surface``, as a rational multiple of `2\pi`, computed from the holonomy
    of its loop.

    This is a helper function for the exact angle of a vertex whose corners
    have irrational angles; it raises a ``ValueError`` when the angle is not
    rational.

    EXAMPLES::

        sage: from flatsurf import HyperbolicPlane
        sage: from flatsurf.geometry.hyperbolic_surface import MutableOrientedHyperbolicSurface
        sage: from flatsurf.geometry.holonomy import _holonomy_angle
        sage: H = HyperbolicPlane(QQ)
        sage: T = MutableOrientedHyperbolicSurface(QQ)
        sage: T.add_polygon(H.polygon(vertices=[(0, 0), (1/2, 0), (0, 1/2)]))
        0
        sage: T.add_polygon(H.polygon(vertices=[(1/2, 0), (1/2, 1/2), (0, 1/2)]))
        1
        sage: T.glue((0, 1), (1, 2)); T.glue((0, 0), (0, 2)); T.glue((1, 0), (1, 1))
        sage: T.set_immutable()
        sage: _holonomy_angle(T, T(1, 0))
        1/2
        sage: _holonomy_angle(T, T(0, 0))
        1/4
        sage: _holonomy_angle(T, T(1, 1))
        Traceback (most recent call last):
        ...
        ValueError: angle is not a rational multiple of 2π; set numerical=True to get a numerical approximation

    A sector of the regular octagon, whose angle at the origin has a cosine
    outside the rational numbers::

        sage: x = polygen(QQ)
        sage: K = NumberField(x^4 + 32*x^2 - 32, "r", embedding=RR(0.98))
        sage: r = K.gen(); s2 = r^2/12 + 4/3
        sage: H = HyperbolicPlane(K)
        sage: S = MutableOrientedHyperbolicSurface(K)
        sage: S.add_polygon(H.polygon(vertices=[(0, 0), (r, 0), (r*s2/2, r*s2/2)]))
        0
        sage: S.glue((0, 0), (0, 2)); S.set_immutable()
        sage: _holonomy_angle(S, S(0, 0))
        1/8

    ALGORITHM:

    The loop of the vertex maps to a rotation by `2 \pi a` whose trace is `1 +
    2 \cos(2 \pi a)`, exactly in the base ring. The cosine determines `a`
    modulo `1` up to `a \leftrightarrow 1 - a`: `a = n + \theta` or `a = n +
    1 - \theta` with `\theta` rational in `[0, 1/2]`. The integer `n` and the
    choice come from the numerical total of the corner angles.

    """
    from sage.all import QQ

    from flatsurf.geometry.hyperbolic_polygon import _rational_arccos

    def not_rational():
        return ValueError(
            "angle is not a rational multiple of 2π; set numerical=True to get a numerical approximation"
        )

    # Walk around the vertex through the corners (q, j), the vertex being the
    # start of the edge j of q; the edge j - 1 of q ends at the vertex, so its
    # partner starts there. This is the order of the loops of the fundamental
    # group, and needs only the gluings around the vertex, finitely many even
    # on an infinite surface.
    q0, point = next(iter(vertex.representatives()))
    j0 = surface.polygon(q0).get_point_position(point).get_vertex()
    if surface.opposite_edge(q0, j0) is None:
        # A vertex on the boundary has no loop.
        raise not_rational()
    letters = [(q0, j0)]
    while True:
        q, j = letters[-1]
        corner = surface.opposite_edge(q, (j - 1) % len(surface.polygon(q).vertices()))
        if corner is None:
            raise not_rational()
        if corner == (q0, j0):
            break
        letters.append(corner)

    try:
        g = surface.edge_transformation(*letters[0])
        for letter in letters[1:]:
            g = g * surface.edge_transformation(*letter)
    except ValueError:
        # The isometry of a self-glued edge may not be defined over the base
        # ring.
        raise not_rational() from None

    cos = (g.trace() - 1) / 2
    if cos == 1:
        thetas = [QQ(0)]
    elif cos == -1:
        thetas = [QQ((1, 2))]
    elif cos**2 < 1:
        sign = 1 if cos > 0 else (-1 if cos < 0 else 0)
        theta = _rational_arccos(sign, cos**2)
        if theta is None:
            raise not_rational()
        thetas = [theta, 1 - theta]
    else:
        raise not_rational()

    # The numerical angle of a corner is computed in double precision with
    # an arccosine, ill-conditioned near ±1, which loses half of the 53
    # bits: its error is below 2^-26 turns, and the tolerance below allows
    # 2^-20 per corner. The candidates n + θ and n + 1 - θ are rationals of
    # denominator at most the bound B of _rational_arccos, so two distinct
    # ones are at least 1/B apart; the total lies within the tolerance of
    # exactly one of them unless 1/B is below twice the tolerance, which is
    # detected as an ambiguity.
    total = surface._angle_vertex(vertex, numerical=True)
    tolerance = len(vertex.representatives()) * 2.0**-20

    close = []
    for theta in thetas:
        candidate = round(total - float(theta)) + theta
        if candidate > 0 and abs(float(candidate) - total) <= tolerance:
            close.append(candidate)

    if len(set(close)) != 1:
        raise not_rational()

    return QQ(close[0])
