r"""
The holonomy representation of a cone surface.

The holonomy representation of a flat or hyperbolic cone surface `S` built
from finitely many polygons is the morphism from the fundamental group of `S`
punctured at its vertices to the group of orientation preserving isometries
of the plane (Euclidean or hyperbolic) that sends a closed walk to the
isometry obtained by developing the polygons it crosses.

Conventions:

- **Product.** A walk is the sequence of the edges ``(label, edge)``
  through which it enters its successive polygons, see
  :class:`~flatsurf.geometry.fundamental_group.FundamentalGroup`. The walk
  entering through `h_0, \dots, h_{k-1}` maps to `U(h_0) U(h_1) \cdots
  U(h_{k-1})` where `U(h)` is the ``edge_transformation`` of `h`, which sends
  the coordinates of the polygon of `h` to the coordinates of the polygon of
  the edge glued to `h`. The product thus sends the coordinates of the last
  polygon into those of the base polygon. Since the inverse of a walk crosses
  the edges glued to its letters in reverse order, and `U` of the edge glued
  to `h` is the inverse of `U(h)`, this is a homomorphism.

- **Order.** Isometries compose from right to left: in the image `U(h_0)
  \cdots U(h_{k-1})` of a walk, the isometry of the last crossed edge acts
  first on a point. Katok (*Fuchsian groups*, 1992) also composes side
  pairings from right to left, so the edges crossed by the walk of a relation
  of his presentation are listed in the reverse order of the side pairings
  acting on a point.

- **Cone points are punctures.** On the surface punctured at its vertices,
  the fundamental group is free on its generators, so the images of the
  generators define the morphism. The loop around a vertex of angle `2 \pi a`
  maps to the counterclockwise rotation by `2 \pi a` about the developed
  vertex. For an orbifold point, `a = 1/m`, the `m`-th power of the loop maps
  to the identity, a relation of the image; for an integral `a`, the loop
  maps to the identity, so the vertex can be filled. The isometry group does
  not record the number of turns: a cone angle `4 \pi` maps to the identity
  as a regular point does.

For a compact orbifold, whose vertices are regular or orbifold points, the
image of the representation is its uniformisation group, generated by the
side pairings of the gluings off a spanning tree of the polygons (Katok
Thm 3.5.4).

EXAMPLES:

The holonomy of the square torus is its group of translations::

    sage: from flatsurf import translation_surfaces
    sage: S = translation_surfaces.square_torus()
    sage: phi = S.holonomy_representation()
    sage: phi
    Holonomy morphism:
      From: Fundamental group of Translation Surface in H_1(0) built from a square punctured at all of its vertices based at polygon 0
      To:   Similarity group over Rational Field
    sage: a, b = phi.domain().gens()
    sage: phi(a)
    (x, y) |-> (x, y - 1)
    sage: phi(b)
    (x, y) |-> (x + 1, y)

"""

