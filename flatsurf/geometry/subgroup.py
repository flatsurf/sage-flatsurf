from sage.structure.parent import Parent
from sage.structure.unique_representation import UniqueRepresentation


class FinitelyGeneratedSubgroup(UniqueRepresentation, Parent):
    r"""
    The subgroup of a group of transformations of the plane generated by
    finitely many of its elements.

    Membership is not decided: it is the word problem of the subgroup, which
    is a Fuchsian group when the subgroup is a discrete group of hyperbolic
    isometries. The elements of the subgroup are those of the ambient group,
    which is their parent.

    INPUT:

    - ``ambient`` -- a group of similarities or of hyperbolic isometries,
      with the methods ``subgroup()`` and ``change_ring()``

    - ``gens`` -- a list or tuple of elements, converted into ``ambient``

    EXAMPLES:

    The subgroup of the similarities of the plane generated by the quarter
    turn and the translation by 1 in the `x` direction::

        sage: from flatsurf.geometry.similarity import SimilarityGroup
        sage: F = SimilarityGroup(QQ)
        sage: rot = F(matrix(QQ, 2, [0, -1, 1, 0]))
        sage: tr = F(1, 0, 1, 0)
        sage: A = F.subgroup([rot, tr])
        sage: A
        Subgroup with 2 generators of Similarity group over Rational Field
        sage: A.gens()
        ((x, y) |-> (-y, x), (x, y) |-> (x + 1, y))
        sage: A.is_orientable()
        True

    The subgroup generated by the rotation of
    :meth:`~flatsurf.geometry.hyperbolic_isometry.HyperbolicIsometryGroup.some_elements`
    about the origin and the product of the reflections in the line `y = 0`
    and in the line through `(1/2, 0)` and `(0, 1/2)`, which fixes `(1/2,
    0)`::

        sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup, _form_reflection
        sage: G3 = HyperbolicIsometryGroup(QQ, form=[1, 2, -3])
        sage: Q = G3.quadratic_form()
        sage: r = G3.some_elements()[2]
        sage: n = Q.inverse() * vector(QQ, (1/2, 0, 1)).cross_product(vector(QQ, (0, 1/2, 1)))
        sage: s = G3(_form_reflection(vector(QQ, (0, 1, 0)), Q) * _form_reflection(n, Q))
        sage: G = G3.subgroup([r, s])
        sage: G
        Subgroup with 2 generators of Group of isometries of the hyperbolic plane over Rational Field with form x^2 + 2*y^2 - 3*z^2
        sage: G.gens()
        ([-1/3  4/3    0]
         [-2/3 -1/3    0]
         [   0    0    1],
         [ -7/17 -24/17  12/17]
         [ 12/17  -5/17  -6/17]
         [ -4/17  -4/17  19/17])
        sage: G.ngens()
        2
        sage: [g.trace() for g in G.gens()]
        [1/3, 7/17]
        sage: (r * s).trace(), (r * ~s).trace()
        (55/17, -9/17)
        sage: G.ambient() is G3
        True
        sage: G.matrix_group()
        Matrix group over Rational Field with 2 generators (
        [-1/3  4/3    0]  [ -7/17 -24/17  12/17]
        [-2/3 -1/3    0]  [ 12/17  -5/17  -6/17]
        [   0    0    1], [ -4/17  -4/17  19/17]
        )

    The trivial subgroup::

        sage: T = G3.subgroup([])
        sage: T
        Subgroup with 0 generators of Group of isometries of the hyperbolic plane over Rational Field with form x^2 + 2*y^2 - 3*z^2
        sage: T.gens()
        ()
        sage: F.subgroup([]).gens()
        ()

    Membership is not decided::

        sage: r in G
        Traceback (most recent call last):
        ...
        NotImplementedError: membership in a finitely generated subgroup is not decided
        sage: G(r)
        Traceback (most recent call last):
        ...
        NotImplementedError: membership in a finitely generated subgroup is not decided
        sage: rot in A
        Traceback (most recent call last):
        ...
        NotImplementedError: membership in a finitely generated subgroup is not decided

    TESTS:

    The subgroup is determined by the ambient group and the generators, in
    their order::

        sage: G3.subgroup([r, s]) is G
        True
        sage: G3.subgroup([s, r]) is G
        False
        sage: loads(dumps(G)) is G
        True
        sage: F.subgroup([rot, tr]) is A
        True
        sage: loads(dumps(A)) is A
        True

    The tests that check that an element, the identity or the generators,
    lies in the subgroup are skipped, since membership is not decided and
    the parent of these elements is the ambient group::

        sage: skip = ["_test_an_element", "_test_one", "_test_some_elements"]
        sage: TestSuite(G).run(skip=skip)
        sage: TestSuite(T).run(skip=skip)
        sage: TestSuite(A).run(skip=skip)
        sage: TestSuite(F.subgroup([])).run(skip=skip)

    """

    @staticmethod
    def __classcall__(cls, ambient, gens):
        r"""
        Create the subgroup with its generators converted into ``ambient``,
        as a tuple, which is the key of the unique representation.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup, HyperbolicIsometrySubgroup
            sage: G = HyperbolicIsometryGroup(AA)
            sage: g = HyperbolicIsometryGroup(QQ).an_element()
            sage: HyperbolicIsometrySubgroup(G, [g]) is G.subgroup((G(g),))
            True

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(AA)
            sage: h = SimilarityGroup(QQ).an_element()
            sage: F.subgroup([h]) is F.subgroup((F(h),))
            True

        """
        return super().__classcall__(cls, ambient, tuple(ambient(g) for g in gens))

    def __init__(self, ambient, gens):
        from sage.categories.groups import Groups

        self._ambient = ambient
        self._gens = gens
        Parent.__init__(self, category=Groups())

    def ambient(self):
        r"""
        Return the group of transformations of which this is a subgroup.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G.an_element()]).ambient() is G
            True

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F.an_element()]).ambient() is F
            True

        """
        return self._ambient

    def gens(self):
        r"""
        Return the generators of this subgroup, elements of the ambient group.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G.an_element()]).gens()
            ([ 7 -4  8]
             [ 4 -1  4]
             [ 8 -4  9],)

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F.an_element()]).gens()
            ((x, y) |-> (3*x + 4*y + 2, 4*x - 3*y - 1),)

        """
        return self._gens

    def ngens(self):
        r"""
        Return the number of generators of this subgroup.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup(G.some_elements()).ngens()
            7

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F.an_element(), F.one()]).ngens()
            2

        """
        return len(self._gens)

    def one(self):
        r"""
        Return the identity, an element of the ambient group.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([]).one() == G.one()
            True

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([]).one() == F.one()
            True

        """
        return self._ambient.one()

    def _an_element_(self):
        r"""
        Return an element of this subgroup, of the ambient group.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G.an_element()]).an_element() == G.an_element()
            True
            sage: G.subgroup([]).an_element().is_one()
            True

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F.an_element()]).an_element() == F.an_element()
            True
            sage: F.subgroup([]).an_element().is_one()
            True

        """
        if self._gens:
            return self._gens[0]
        return self.one()

    def some_elements(self):
        r"""
        Return some elements of this subgroup, of the ambient group: the
        identity and the generators.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: [g.trace() for g in G.subgroup(G.some_elements()[3:5]).some_elements()]
            [3, 15, 7/2]

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F((1, 0))]).some_elements()
            [(x, y) |-> (x, y), (x, y) |-> (x + 1, y)]

        """
        return [self.one()] + list(self._gens)

    def base_ring(self):
        r"""
        Return the base ring of the ambient group.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: HyperbolicIsometryGroup(AA).subgroup([]).base_ring()
            Algebraic Real Field

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: SimilarityGroup(QQ).subgroup([]).base_ring()
            Rational Field

        """
        return self._ambient.base_ring()

    def change_ring(self, ring):
        r"""
        Return the subgroup of the ambient group over ``ring``, with the same
        geometry, generated by the generators of this subgroup.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ, form=[1, 2, -3])
            sage: H = G.subgroup([G.some_elements()[2]]).change_ring(AA)
            sage: H
            Subgroup with 1 generator of Group of isometries of the hyperbolic plane over Algebraic Real Field with form x^2 + 2*y^2 - 3*z^2
            sage: H.change_ring(QQ).ambient() is G
            True

        A generator must have its entries in ``ring``::

            sage: K.<a> = NumberField(x^2 - 3, embedding=AA(3).sqrt())
            sage: GK = HyperbolicIsometryGroup(K)
            sage: g = GK([[a/2, -1/2, 0], [1/2, a/2, 0], [0, 0, 1]])
            sage: GK.subgroup([g]).change_ring(QQ)
            Traceback (most recent call last):
            ...
            TypeError: ...

        The same for similarities of the plane::

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: B = F.subgroup([F(matrix(QQ, 2, [0, -1, 1, 0]))])
            sage: B.change_ring(AA)
            Subgroup with 1 generator of Similarity group over Algebraic Real Field
            sage: B.change_ring(AA).change_ring(QQ) is B
            True

        """
        return self._ambient.change_ring(ring).subgroup(self._gens)

    def matrix_group(self):
        r"""
        Return the group of matrices generated by the matrices of the
        generators, over the base ring.

        With no generator, this is the group generated by the identity
        matrix.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G.some_elements()[1]]).matrix_group()
            Matrix group over Rational Field with 1 generators (
            [ 0 -1  0]
            [ 1  0  0]
            [ 0  0  1]
            )
            sage: G.subgroup([]).matrix_group()
            Matrix group over Rational Field with 1 generators (
            [1 0 0]
            [0 1 0]
            [0 0 1]
            )

        The matrices of similarities are the 3×3 affine matrices::

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: F.subgroup([F(matrix(QQ, 2, [1, 0, 0, -1]))]).matrix_group()
            Matrix group over Rational Field with 1 generators (
            [ 1  0  0]
            [ 0 -1  0]
            [ 0  0  1]
            )

        """
        from sage.groups.matrix_gps.finitely_generated import MatrixGroup
        from sage.matrix.special import identity_matrix

        gens = [g.matrix() for g in self._gens]
        if not gens:
            gens = [identity_matrix(self.base_ring(), 3)]
        return MatrixGroup(gens)

    def is_orientable(self):
        r"""
        Return whether every element of this subgroup preserves the
        orientation.

        The orientation is a character of the ambient group, with values `\pm
        1`, so the generators decide: the subgroup preserves the orientation
        if and only if each of its generators does, in particular when it has
        no generator.

        EXAMPLES::

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: rot = F(matrix(QQ, 2, [0, -1, 1, 0]))
            sage: r = F(matrix(QQ, 2, [1, 0, 0, -1]))
            sage: F.subgroup([rot]).is_orientable()
            True
            sage: F.subgroup([rot, r]).is_orientable()
            False
            sage: F.subgroup([]).is_orientable()
            True

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G(diagonal_matrix([1, -1, 1]))]).is_orientable()
            False

        """
        return all(g.is_orientable() for g in self._gens)

    def orientation_preserving_subgroup(self):
        r"""
        Return the subgroup of the elements of this subgroup that preserve the
        orientation, which has index 1 or 2.

        OUTPUT:

        This subgroup itself when it is orientable, and otherwise the subgroup
        of the ambient group generated by at most `2n - 1` elements, for `n`
        the number of generators of this subgroup.

        EXAMPLES:

        A subgroup of similarities generated by a quarter turn and a
        reflection; the elements of the subgroup that preserve the orientation
        are the powers of the quarter turn, generated by the quarter turn and
        by its conjugate by the reflection, its inverse::

            sage: from flatsurf.geometry.similarity import SimilarityGroup
            sage: F = SimilarityGroup(QQ)
            sage: rot = F(matrix(QQ, 2, [0, -1, 1, 0]))
            sage: r = F(matrix(QQ, 2, [1, 0, 0, -1]))
            sage: B = F.subgroup([rot, r])
            sage: B.orientation_preserving_subgroup().gens()
            ((x, y) |-> (-y, x), (x, y) |-> (y, -x))

        An orientable subgroup is its own subgroup of orientation preserving
        elements::

            sage: A = F.subgroup([rot])
            sage: A.orientation_preserving_subgroup() is A
            True

        The group generated by two reflections of the hyperbolic plane, whose
        product is a rotation about the fixed point of the second one::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup, _form_reflection
            sage: G3 = HyperbolicIsometryGroup(QQ, form=[1, 2, -3])
            sage: Q = G3.quadratic_form()
            sage: n = Q.inverse() * vector(QQ, (1/2, 0, 1)).cross_product(vector(QQ, (0, 1/2, 1)))
            sage: m1 = G3(_form_reflection(vector(QQ, (0, 1, 0)), Q))
            sage: m2 = G3(_form_reflection(n, Q))
            sage: P = G3.subgroup([m1, m2]).orientation_preserving_subgroup()
            sage: P.ngens()
            2
            sage: [g.trace() for g in P.gens()]
            [7/17, 7/17]
            sage: all(g.is_orientable() for g in P.gens())
            True

        ALGORITHM:

        Let `s` be the first generator that reverses the orientation. The
        kernel of the orientation character has index 2 and the transversal
        `\{1, s\}`, so by the Reidemeister-Schreier method it is generated by
        the elements `u \cdot g \cdot \overline{ug}^{-1}` for `u` in the
        transversal and `g` a generator, where `\overline{x}` is the element
        of the transversal in the coset of `x`. This gives, in the order of the
        generators: for a generator `g` that preserves the orientation, `g`
        and `s g s^{-1}`; for a generator `t` that reverses it, `t s^{-1}` and
        `s t`. The generators equal to the identity are dropped.
        """
        if self.is_orientable():
            return self

        s = next(g for g in self._gens if not g.is_orientable())
        s_inverse = ~s
        gens = []
        for g in self._gens:
            if g.is_orientable():
                gens.append(g)
                gens.append(s * g * s_inverse)
            else:
                gens.append(g * s_inverse)
                gens.append(s * g)
        return self._ambient.subgroup([g for g in gens if not g.is_one()])

    def __contains__(self, x):
        r"""
        Return whether ``x`` is an element of this subgroup, which is not
        decided.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.one() in G.subgroup([])
            Traceback (most recent call last):
            ...
            NotImplementedError: membership in a finitely generated subgroup is not decided

        """
        raise NotImplementedError(
            "membership in a finitely generated subgroup is not decided"
        )

    def _element_constructor_(self, x):
        r"""
        Return ``x`` as an element of this subgroup, which needs membership.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup([G.an_element()])(G.an_element())
            Traceback (most recent call last):
            ...
            NotImplementedError: membership in a finitely generated subgroup is not decided

        """
        raise NotImplementedError(
            "membership in a finitely generated subgroup is not decided"
        )

    def _repr_(self):
        r"""
        Return a printable representation of this subgroup.

        EXAMPLES::

            sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
            sage: G = HyperbolicIsometryGroup(QQ)
            sage: G.subgroup(G.some_elements()[1:3])
            Subgroup with 2 generators of Group of isometries of the hyperbolic plane over Rational Field

        """
        n = len(self._gens)
        generators = "generator" if n == 1 else "generators"
        return f"Subgroup with {n} {generators} of {self._ambient}"
