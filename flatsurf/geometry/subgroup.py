r"""
Finitely generated subgroups of the groups of transformations of the plane.

A :class:`FinitelyGeneratedSubgroup` is the subgroup of a group of similarities
of the Euclidean plane (:class:`~flatsurf.geometry.similarity.SimilarityGroup`)
or of a group of isometries of the hyperbolic plane
(:class:`~flatsurf.geometry.hyperbolic_isometry.HyperbolicIsometryGroup`)
generated by finitely many elements. Such a group has no decision procedure
for membership, but the orientation of its elements is a character, so
whether it preserves the orientation, and its subgroup of index 2 of
orientation preserving elements, are computed from the generators.

EXAMPLES:

In the group of similarities of the plane, the quarter turn and the reflection
in the `x`-axis generate a subgroup with reversing elements, whose subgroup of
orientation preserving elements is generated by the quarter turn and its
conjugate::

    sage: from flatsurf.geometry.similarity import SimilarityGroup
    sage: F = SimilarityGroup(QQ)
    sage: rot = F(matrix(QQ, 2, [0, -1, 1, 0]))
    sage: r = F(matrix(QQ, 2, [1, 0, 0, -1]))
    sage: B = F.subgroup([rot, r])
    sage: B.is_orientable()
    False
    sage: B.orientation_preserving_subgroup().gens()
    ((x, y) |-> (-y, x), (x, y) |-> (y, -x))

In the group of isometries of the hyperbolic plane::

    sage: from flatsurf.geometry.hyperbolic_isometry import HyperbolicIsometryGroup
    sage: G = HyperbolicIsometryGroup(QQ)
    sage: m = G(diagonal_matrix([1, -1, 1]))
    sage: G.subgroup([m]).orientation_preserving_subgroup().gens()
    ()
"""

