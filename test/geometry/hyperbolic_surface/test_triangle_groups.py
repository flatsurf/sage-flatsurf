import pytest

from sage.all import AA, QQ, RIF, RR, ZZ, NumberField, polygen

from flatsurf import HyperbolicPlane, fuchsian_groups

from hyperbolic_surface_oracles import COMPACT_SIGNATURES, TRIANGLE_DOUBLES

x = polygen(QQ, "x")


def field(polynomial):
    r"""
    Return ``QQ`` for a polynomial of degree 1, otherwise the number field
    it defines.
    """
    if polynomial.degree() == 1:
        return QQ
    return NumberField(polynomial, "b")


def assert_generators(G, periods):
    r"""
    Check that the generators of ``G`` have the orders ``periods`` and
    multiply to the identity.
    """
    gens = G.gens()
    assert len(gens) == 3
    for g, m in zip(gens, periods):
        assert (g**m).is_one()
        assert not any((g**d).is_one() for d in ZZ(m).divisors()[:-1])
    g1, g2, g3 = gens
    assert (g1 * g2 * g3).is_one()


@pytest.mark.parametrize(
    "periods,polynomial,standard_degree",
    [
        ((2, 3, 7), x**3 - 7 * x - 7, 6),
        ((2, 4, 5), x**2 - x - 1, 4),
        ((2, 4, 6), x, 2),
        ((3, 3, 4), x**2 - 2, None),
        ((3, 4, 4), x, 2),
        ((4, 4, 4), x**2 - 2, None),
        (
            (3, 5, 7),
            x**6 - x**5 - 7 * x**4 + 2 * x**3 + 7 * x**2 - 2 * x - 1,
            12,
        ),
    ],
)
def test_triangle_group(periods, polynomial, standard_degree):
    G = fuchsian_groups.triangle(*periods)
    K = G.base_ring()
    assert K.degree() == polynomial.degree()
    if K is not QQ:
        assert K.is_isomorphic(field(polynomial))
    assert G.invariant_trace_field().degree() == polynomial.degree()
    assert_generators(G, periods)

    if standard_degree is not None:
        G = fuchsian_groups.triangle(*periods, standard=True)
        assert G.base_ring().degree() == standard_degree
        assert G.hyperbolic_plane() is HyperbolicPlane(G.base_ring())
        assert_generators(G, periods)


def test_triangle_group_degree_24():
    G = fuchsian_groups.triangle(5, 7, 8)
    assert G.base_ring().degree() == 24
    assert_generators(G, (5, 7, 8))


@pytest.mark.parametrize(
    "periods",
    [periods for g, periods, _ in COMPACT_SIGNATURES if g == 0 and len(periods) == 3],
)
def test_invariant_trace_field(periods):
    k0 = next(
        k0
        for vertex_periods, _, _, k0 in TRIANGLE_DOUBLES
        if sorted(vertex_periods) == list(periods)
    )
    K = fuchsian_groups.triangle(*periods).base_ring()
    assert K.is_isomorphic(field(x.parent()(k0)))


def test_base_ring():
    G = fuchsian_groups.triangle(3, 4, 4, base_ring=AA)
    assert G.base_ring() is AA
    assert_generators(G, (3, 4, 4))

    # The field of x^4 - 2x^2 - 1 contains sqrt(2) = s^2 - 1 without a
    # coercion from the invariant trace field Q(sqrt(2)) of (3, 3, 4).
    L = NumberField(
        x**4 - 2 * x**2 - 1,
        "s",
        embedding=AA.polynomial_root(x**4 - 2 * x**2 - 1, RIF(1.5, 1.6)),
    )
    G = fuchsian_groups.triangle(3, 3, 4, base_ring=L)
    assert G.base_ring() is L
    assert_generators(G, (3, 3, 4))


@pytest.mark.parametrize(
    "periods,message",
    [
        ((1, 4, 4), "the period 1 is not an integer at least 2"),
        ((QQ(5) / 2, 4, 4), "the period 5/2 is not an integer at least 2"),
        (
            (2, 3, 6),
            r"the triangle group \(2, 3, 6\) is euclidean, not hyperbolic",
        ),
        (
            (2, 4, 4),
            r"the triangle group \(2, 4, 4\) is euclidean, not hyperbolic",
        ),
        (
            (2, 3, 5),
            r"the triangle group \(2, 3, 5\) is spherical, not hyperbolic",
        ),
        (
            (2, 2, 7),
            r"the triangle group \(2, 2, 7\) is spherical, not hyperbolic",
        ),
    ],
)
def test_refused(periods, message):
    with pytest.raises(ValueError, match=message):
        fuchsian_groups.triangle(*periods)


def test_refused_ring():
    with pytest.raises(
        ValueError, match="the coordinates of the polygon do not lie in Rational Field"
    ):
        fuchsian_groups.triangle(2, 3, 7, base_ring=QQ)
    with pytest.raises(
        ValueError, match="the coordinates of the polygon do not lie in Rational Field"
    ):
        fuchsian_groups.triangle(3, 4, 4, base_ring=QQ, standard=True)
    with pytest.raises(
        ValueError,
        match="the ring must be exact, not Real Field with 53 bits of precision",
    ):
        fuchsian_groups.triangle(3, 4, 4, base_ring=RR)
