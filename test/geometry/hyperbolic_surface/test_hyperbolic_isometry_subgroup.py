import re

import pytest

import sage.misc.sage_unittest

from sage.all import AA, QQ, NumberField, identity_matrix, matrix, polygen, vector

from flatsurf.geometry.hyperbolic_isometry import (
    HyperbolicIsometryGroup,
    _form_reflection,
)


MEMBERSHIP = re.escape("membership in a finitely generated subgroup is not decided")
SKIP = ["_test_an_element", "_test_one", "_test_some_elements"]

R = matrix(QQ, [[-QQ(1) / 3, QQ(4) / 3, 0], [-QQ(2) / 3, -QQ(1) / 3, 0], [0, 0, 1]])
S = matrix(QQ, [[-7, -24, 12], [12, -5, -6], [-4, -4, 19]]) / 17


@pytest.fixture
def G3():
    return HyperbolicIsometryGroup(QQ, form=[1, 2, -3])


@pytest.fixture
def K():
    x = polygen(QQ)
    return NumberField(x**2 - 3, "a", embedding=AA(3).sqrt())


@pytest.fixture
def r(G3):
    return G3.some_elements()[2]


@pytest.fixture
def s(G3):
    Q = G3.quadratic_form()
    n = Q.inverse() * vector(QQ, (QQ(1) / 2, 0, 1)).cross_product(
        vector(QQ, (0, QQ(1) / 2, 1))
    )
    return G3(_form_reflection(vector(QQ, (0, 1, 0)), Q) * _form_reflection(n, Q))


def test_generators(G3, r, s):
    G = G3.subgroup([r, s])
    assert G.gens() == (r, s)
    assert [g.matrix() for g in G.gens()] == [R, S]
    assert G.ngens() == 2
    assert [g.trace() for g in G.gens()] == [QQ(1) / 3, QQ(7) / 17]
    assert (r * s).trace() == QQ(55) / 17
    assert (r * ~s).trace() == -QQ(9) / 17
    assert r.fixed_point().coordinates(model="klein") == (0, 0)
    assert s.fixed_point().coordinates(model="klein") == (QQ(1) / 2, 0)
    assert G.ambient() is G3
    assert G.base_ring() is QQ
    assert G.quadratic_form() == G3.quadratic_form()
    assert G.hyperbolic_plane() is G3.hyperbolic_plane()
    assert G.one() == G3.one()
    assert repr(G) == f"Subgroup with 2 generators of {G3!r}"
    assert repr(G3.subgroup([r])) == f"Subgroup with 1 generator of {G3!r}"
    sage.misc.sage_unittest.TestSuite(G).run(skip=SKIP, raise_on_failure=True)


def test_equality_and_hash(G3, r, s):
    G = G3.subgroup([r, s])
    H = G3.subgroup((G3(R), G3(S)))
    assert G is H
    assert G == H
    assert hash(G) == hash(H)
    assert G3.subgroup([s, r]) != G
    assert HyperbolicIsometryGroup(AA, form=[1, 2, -3]).subgroup([r, s]) != G


def test_trivial_subgroup(G3):
    T = G3.subgroup([])
    assert T.gens() == ()
    assert T.ngens() == 0
    assert repr(T) == f"Subgroup with 0 generators of {G3!r}"
    assert T.invariant_trace_field() is QQ
    assert list(T.matrix_group().gens())[0].matrix() == identity_matrix(QQ, 3)
    sage.misc.sage_unittest.TestSuite(T).run(skip=SKIP, raise_on_failure=True)


def test_matrix_group(G3, r, s):
    M = G3.subgroup([r, s]).matrix_group()
    assert M.base_ring() is QQ
    assert [g.matrix() for g in M.gens()] == [R, S]
    assert repr(M).startswith("Matrix group over Rational Field with 2 generators (")


def test_change_ring(G3, K, r, s):
    G = G3.subgroup([r, s])
    GK = G.change_ring(K)
    assert GK.ambient() is HyperbolicIsometryGroup(K, form=[1, 2, -3])
    assert [g.matrix() for g in GK.gens()] == [R, S]
    assert GK.change_ring(QQ) is G

    a = K.gen()
    rotation = HyperbolicIsometryGroup(K)(
        [[a / 2, -QQ(1) / 2, 0], [QQ(1) / 2, a / 2, 0], [0, 0, 1]]
    )
    with pytest.raises(TypeError):
        HyperbolicIsometryGroup(K).subgroup([rotation]).change_ring(QQ)


def test_membership_refused(G3, r, s):
    G = G3.subgroup([r, s])
    with pytest.raises(NotImplementedError, match=MEMBERSHIP):
        r in G
    with pytest.raises(NotImplementedError, match=MEMBERSHIP):
        G(r)


def test_invariant_trace_field(G3, K, r, s):
    G = G3.subgroup([r, s])
    assert G.invariant_trace_field() is QQ
    f = G3.hyperbolic_plane().standard_form_isometry(K)
    assert f(G).invariant_trace_field() is QQ


def test_image_under_isomorphism(G3, K, r, s):
    a = K.gen()
    f = G3.hyperbolic_plane().standard_form_isometry(K)
    assert f.matrix() == matrix(
        K, [[7 * a / 12, 0, -QQ(5) / 4], [0, 1, 0], [-5 * a / 12, 0, QQ(7) / 4]]
    )
    G = f(G3.subgroup([r, s]))
    assert G.ambient() is HyperbolicIsometryGroup(K)
    assert [g.matrix() for g in G.gens()] == [
        matrix(
            K,
            [
                [-QQ(31) / 18, 7 * a / 9, -QQ(35) / 18],
                [-7 * a / 9, -QQ(1) / 3, -5 * a / 9],
                [QQ(35) / 18, -5 * a / 9, QQ(43) / 18],
            ],
        ),
        matrix(
            K,
            [
                [35 * a / 51 - QQ(409) / 204, -14 * a / 17 + QQ(5) / 17, 37 * a / 51 - QQ(455) / 204],
                [14 * a / 17 - QQ(5) / 17, -QQ(5) / 17, 10 * a / 17 - QQ(7) / 17],
                [-37 * a / 51 + QQ(455) / 204, 10 * a / 17 - QQ(7) / 17, -35 * a / 51 + QQ(553) / 204],
            ],
        ),
    ]
    assert [g.trace() for g in G.gens()] == [QQ(1) / 3, QQ(7) / 17]
    assert f(G3.subgroup([r, s]).change_ring(K)) is G


@pytest.fixture
def m1(G3):
    Q = G3.quadratic_form()
    return G3(_form_reflection(vector(QQ, (0, 1, 0)), Q))


@pytest.fixture
def m2(G3):
    Q = G3.quadratic_form()
    n = Q.inverse() * vector(QQ, (QQ(1) / 2, 0, 1)).cross_product(
        vector(QQ, (0, QQ(1) / 2, 1))
    )
    return G3(_form_reflection(n, Q))


def test_group_change_ring(G3, K):
    GK = G3.change_ring(K)
    assert GK is HyperbolicIsometryGroup(K, form=[1, 2, -3])
    assert GK.change_ring(QQ) is G3
    assert HyperbolicIsometryGroup(QQ).change_ring(AA) is HyperbolicIsometryGroup(AA)


def test_is_orientable(G3, r, s, m1, m2):
    assert m1.det() == m2.det() == -1
    assert (m1 * m2).trace() == QQ(7) / 17
    assert G3.subgroup([r, s]).is_orientable()
    assert G3.subgroup([]).is_orientable()
    assert not G3.subgroup([m1]).is_orientable()
    assert not G3.subgroup([r, m1]).is_orientable()
    assert G3.subgroup([r, s]).orientation_preserving_subgroup() is G3.subgroup(
        [r, s]
    )


def test_orientation_preserving_subgroup(G3, r, m1, m2):
    P = G3.subgroup([r, m1]).orientation_preserving_subgroup()
    assert (m1 * r * ~m1 * r).is_one()
    assert P.gens() == (r,)
    assert [g.trace() for g in P.gens()] == [QQ(1) / 3]
    assert P.is_orientable()
    assert P.invariant_trace_field() is QQ
    assert G3.subgroup([r, m1]).invariant_trace_field() is QQ

    P = G3.subgroup([m1, m2]).orientation_preserving_subgroup()
    assert P.gens() == (m2 * ~m1,)
    assert [g.trace() for g in P.gens()] == [QQ(7) / 17]
    assert G3.subgroup([m1, m2]).invariant_trace_field() is QQ

    T = G3.subgroup([m1]).orientation_preserving_subgroup()
    assert T.gens() == ()
    assert T.invariant_trace_field() is QQ


def test_extended_triangle_group():
    from flatsurf import hyperbolic_polygons

    T = hyperbolic_polygons.triangle(QQ(1) / 4, QQ(1) / 6, QQ(1) / 14)
    GT = T._transformation_group()
    Q = GT.quadratic_form()
    V = [
        vector(list(v.coordinates(model="klein")) + [1]) for v in T.vertices()
    ]
    reflections = [
        GT(_form_reflection(Q.inverse() * V[i].cross_product(V[(i + 1) % 3]), Q))
        for i in range(3)
    ]
    assert all(g.det() == -1 and (g * g).is_one() for g in reflections)

    W = GT.subgroup(reflections)
    assert not W.is_orientable()
    P = W.orientation_preserving_subgroup()
    assert P.ngens() == 2
    assert sorted(g.trace() for g in P.gens()) == [-1, 0]

    F = W.invariant_trace_field()
    assert F.degree() == 3
    assert F.polynomial() == polygen(QQ) ** 3 - 7 * polygen(QQ) - 7
